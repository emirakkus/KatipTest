export const buildCatalog = (): TextCatalogItem[] => {
  const years = [2021, 2022, 2023, 2024, 2025, 2026];
  const institutions: TextCatalogItem['institution'][] = ['Adliye Zabıt Katipliği', 'İcra Katipliği', 'Danıştay', 'Yargıtay', 'Genel Hukuk'];

  const makeItems = (texts: string[], difficulty: 'easy' | 'medium' | 'hard') => texts.map((text, i) => {
    const title = text.split(' ').slice(0, 4).join(' ') + '...';
    const words = text.trim().split(/\s+/).length;
    return {
      id: `${difficulty}-${i}`,
      title,
      text,
      year: years[i % years.length],
      institution: institutions[i % institutions.length],
      difficulty,
      words,
      chars: text.replace(/\s/g, '').length
    } as TextCatalogItem;
  });

  return [...makeItems(TEXTS_EASY, 'easy'), ...makeItems(TEXTS_MEDIUM, 'medium'), ...makeItems(TEXTS_HARD, 'hard')];
};

